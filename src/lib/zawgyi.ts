function isFontAvailable(fontName: string): boolean {
  if (typeof document === "undefined") return false;

  try {
    if (document.fonts.check(`16px "${fontName}"`)) return true;
  } catch {}

  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d");
  if (!ctx) return false;
  const test = "ကabc123";
  ctx.font = "16px monospace";
  const baseline = ctx.measureText(test).width;
  ctx.font = `16px "${fontName}", monospace`;
  return baseline !== ctx.measureText(test).width;
}

export function detectZawgyiSystem(): boolean {
  const fonts = ["Zawgyi-One", "ZawgyiOne", "Zawgyi One", "Myanmar3"];
  return fonts.some(isFontAvailable);
}

export function unicodeToZawgyi(text: string): string {
  return unicodeToZawgyiStr(text);
}
