// Unicode → Zawgyi converter — ported from google/myanmar-tools (Apache 2.0)
// Self-contained, no npm dependency, browser compatible.

type TranslitRule = { p: RegExp; s: string };

function runPhase(rules: TranslitRule[], input: string): string {
  let out = "";
  let mid = input;
  while (mid.length > 0) {
    let matched = false;
    for (const rule of rules) {
      const m = mid.match(rule.p);
      if (m != null) {
        matched = true;
        const rightSize = mid.length - m[0].length;
        mid = mid.replace(rule.p, rule.s);
        const newStart = mid.length - rightSize;
        out += mid.substring(0, newStart);
        mid = mid.substring(newStart);
        break;
      }
    }
    if (!matched) {
      out += mid[0];
      mid = mid.substring(1);
    }
  }
  return out;
}

